package admin

import (
	"github.com/gin-gonic/gin"
	"net/http"
)

// Register installs administrator authentication and permissions.
func (s *Handler) Register(router *gin.Engine) {
	router.GET("/api/auth/configuration", func(c *gin.Context) {
		c.JSON(http.StatusOK, gin.H{"showDefaultCredentials": s.Config.DefaultCredentialHint()})
	})
	router.GET("/api/auth/csrf", s.csrf)
	router.POST("/api/auth/login", s.login)
	router.GET("/api/auth/user", s.requireUser, s.current)
	router.POST("/api/auth/logout", s.requireUser, s.logout)
	group := router.Group("/api/players", s.requireUser, s.permission("players.view"))
	group.GET("/accounts", s.accounts)
	group.GET("/account-deletions", s.permission("players.edit"), s.accountDeletions)
	group.DELETE("/accounts/:accountId", s.permission("players.edit"), s.deleteAccount)
	group.GET("/accounts/:accountId/deletion", s.permission("players.edit"), s.accountDeletion)
	group.POST("/accounts/:accountId/deletion/retry", s.permission("players.edit"), s.retryAccountDeletion)
	group.POST("/accounts/batch", s.permission("players.edit"), s.batchAccounts)
	group.POST("/accounts", s.permission("players.edit"), s.createAccount)
	group.PATCH("/accounts/:accountId", s.permission("players.edit"), s.updateAccount)
	group.POST("/accounts/:accountId/password", s.permission("players.edit"), s.accountPassword)
	group.GET("/characters", s.characters)
	group.GET("/characters/:charId", s.character)
	group.GET("/login-logs", s.loginLogs)
	data := router.Group("/api/game-data", s.requireUser, s.permission("game-data.view"))
	data.GET("/items", s.items)
	data.GET("/items/:itemId", s.item)
	data.GET("/items/:itemId/icon", s.CatalogAsset("icon", "itemId"))
	data.GET("/items/:itemId/illustration", s.CatalogAsset("illustration", "itemId"))
	data.GET("/monsters", s.monsters)
	data.GET("/monsters/:monsterId", s.monster)
	data.GET("/monsters/:monsterId/image", s.CatalogAsset("monster", "monsterId"))
	data.GET("/npcs", s.npcs)
	data.GET("/npcs/:spriteId/image", s.CatalogAsset("npc", "spriteId"))
	data.GET("/maps/:map/npcs", s.mapNPCs)
	settings := router.Group("/api/settings", s.requireUser, s.permission("settings.manage"))
	settings.POST("/game-settings/revisions/:revisionId/resume", s.resumeSettings)
	settings.PUT("/game-settings", s.applySettings)
	settings.GET("/game-settings/history", s.gameSettingsHistory)
	settings.GET("/game-settings", s.readSettings)
	settings.GET("/game-data", s.catalogVersions)
	settings.GET("/game-data/history", s.catalogHistory)
	data.GET("/maps", s.maps)
	data.GET("/maps/:map/image", s.mapImage)
	control := router.Group("/api/operations/game-control", s.requireUser, s.permission("operations.game-control"))
	control.GET("/capabilities", s.capabilities)
	control.GET("/battle-config", s.battleConfig)
	control.GET("/characters/:characterId", s.characterSnapshot)
	control.POST("/commands", s.submitCommand)
	control.GET("/commands/:commandId", s.showCommand)
	operations := router.Group("/api/operations", s.requireUser, s.permission("operations.item-grant"))
	operations.GET("/item-grant-items", s.grantItems)
	operations.GET("/item-grant-targets", s.grantTargets)
	operations.POST("/item-grants/mail", s.grantItem)
	operations.POST("/zeny-grants", s.grantZeny)
	operations.GET("/item-grants", s.grantHistory)
}
